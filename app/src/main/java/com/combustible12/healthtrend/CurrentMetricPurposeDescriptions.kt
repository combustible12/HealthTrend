 fun resolveKey(key:String):String? {
  val canonical=canonicalMetricKey(key)
  if(canonical in entries)return canonical
  // Preserve the two legacy educational aliases without changing stored metric identity.
  if(canonical=="HIV")return "HIVAB"
  if(canonical=="SYPHILIS")return "TPAB"
  return nameKeys[UnifiedMetricStandard.normalizedName(key)]?.singleOrNull()
 }
